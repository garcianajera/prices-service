CREATE TABLE PRICES (
    ID             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BRAND_ID       BIGINT        NOT NULL,
    START_DATE     TIMESTAMP(0)  NOT NULL,
    END_DATE       TIMESTAMP(0)  NOT NULL,
    PRICE_LIST     BIGINT        NOT NULL,
    PRODUCT_ID     BIGINT        NOT NULL,
    PRIORITY       INT           NOT NULL,
    PRICE          DECIMAL(10,2) NOT NULL,
    CURR           CHAR(3)       NOT NULL,
    LAST_UPDATE    TIMESTAMP(0)  NOT NULL,
    LAST_UPDATE_BY VARCHAR(50)   NOT NULL,
    CONSTRAINT CK_PRICES_DATE_RANGE CHECK (END_DATE >= START_DATE),
    CONSTRAINT CK_PRICES_PRIORITY   CHECK (PRIORITY >= 0),
    CONSTRAINT CK_PRICES_PRICE      CHECK (PRICE >= 0)
);

CREATE INDEX IDX_PRICES_LOOKUP ON PRICES (BRAND_ID, PRODUCT_ID, START_DATE, END_DATE);
